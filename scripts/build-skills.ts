/**
 * Writes skills/<mode>/SKILL.md and skills/<mode>/config.json for every prebuilt research mode,
 * plus skills/README.md, from the published dataset. Set NEXT_PUBLIC_SITE_URL to the deployment
 * URL before running so the remote MCP address points at it.
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { loadPublishedDataset } from "@/lib/db/file-store";
import { MCP_SERVER_NAME, mcpConnection, REQUESTED_CAPABILITIES, TOOLS } from "@/lib/mcp/catalog";
import { buildConfigJson, buildSkill, MODES, modeConfig, PROMPT_VERSION } from "@/lib/skills";
import { buildSkillContext } from "@/lib/skills/context";

const DEFAULT_SITE_URL = "http://localhost:3000";
const siteUrl = (process.env.NEXT_PUBLIC_SITE_URL || DEFAULT_SITE_URL).replace(/\/+$/, "");
if (!/^https?:\/\/[^\s/]+/.test(siteUrl)) throw new Error(`NEXT_PUBLIC_SITE_URL is not a URL: ${siteUrl}`);

const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "skills");
const d = await loadPublishedDataset();
const ctx = buildSkillContext(d, siteUrl);

await fs.mkdir(out, { recursive: true });
const folders = new Map<string, string>();
for (const m of MODES) {
  const config = modeConfig(m.id);
  const skill = buildSkill(config, ctx);
  // The Agent Skills format expects the folder name to equal the skill name.
  const dir = path.join(out, skill.name);
  folders.set(m.id, skill.name);
  await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(path.join(dir, "SKILL.md"), skill.markdown);
  await fs.writeFile(path.join(dir, "config.json"), `${JSON.stringify(buildConfigJson(config, ctx), null, 2)}\n`);
  console.log(`skills/${skill.name}: SKILL.md, config.json`);
}

const conn = mcpConnection(siteUrl);
const readme = [
  "# Research skills",
  "",
  `Generated by \`npm run skills:build\` from dataset ${ctx.datasetVersion} (brief ${PROMPT_VERSION}). Do not edit by hand; change lib/skills and regenerate.`,
  "",
  `Each folder holds a \`SKILL.md\` for assistants that support skills and a \`config.json\` with the same parameters, the matching initiatives, the MCP connection, the JSON Schema for structured output and empty provenance fields. Every brief restricts research to the ${ctx.cohortSize} initiatives in the ballot cohort, requires source citations, treats retrieved content as untrusted, never presents future targets as existing capabilities, sets no ranking weights and leaves decisions to the reviewer.`,
  "",
  "ETHSecurity Intelligence runs no AI model. These files instruct the reviewer's own assistant.",
  "",
  `${ctx.coi.text}`,
  "",
  "| Mode | Folder | Focus |",
  "| --- | --- | --- |",
  ...MODES.map((m) => `| ${m.label} | [${folders.get(m.id)}](./${folders.get(m.id)}/SKILL.md) | ${m.summary} |`),
  "",
  "Custom briefs can be built in the AI Lab (/lab) of the website.",
  "",
  "## MCP connection",
  "",
  `These files were generated with site URL ${siteUrl}.${siteUrl === DEFAULT_SITE_URL ? " That is a local server (`npm run build && npm start`); regenerate with `NEXT_PUBLIC_SITE_URL=<deployment URL> npm run skills:build` for a deployment." : ""}`,
  "",
  `- Remote (Streamable HTTP, stateless, read-only): ${conn.remoteUrl}`,
  `- Local (stdio): \`${conn.stdio.command} ${conn.stdio.args.join(" ")}\`. ${conn.stdio.note}`,
  "",
  ...conn.clients.flatMap((c) => [`${c.name}, \`${c.file}\`:`, "", "```", c.config, "```", ""]),
  "## Tools",
  "",
  `The server \`${MCP_SERVER_NAME}\` exposes ${TOOLS.length} read-only tools. The ${REQUESTED_CAPABILITIES.length} requested capabilities map onto them as follows.`,
  "",
  "| Capability | Tool | How |",
  "| --- | --- | --- |",
  ...REQUESTED_CAPABILITIES.flatMap((name) => TOOLS.flatMap((t) => t.covers.filter((c) => c.name === name).map((c) => `| ${name} | \`${t.name}\` | ${c.how.replace(/\|/g, "\\|")} |`))),
  "",
].join("\n");
await fs.writeFile(path.join(out, "README.md"), readme);
console.log("skills/README.md");
