import { z } from "zod";
import { BLIND_SPOT_LABEL, blindSpots, findInitiative, type BlindSpot } from "@/lib/intelligence/service";
import { handle, IdParam, load, notFound, ok, PAGE_NUMBERS, PageFields, pageOf, paginate, parseQuery } from "@/lib/api/http";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const CATEGORIES = Object.keys(BLIND_SPOT_LABEL) as [BlindSpot["category"], ...BlindSpot["category"][]];
const Query = z
  .object({ initiative: IdParam.optional(), categories: z.array(z.enum(CATEGORIES)).max(CATEGORIES.length).optional(), importance: z.enum(["higher", "standard"]).optional(), ...PageFields })
  .strict();

/** GET /api/v1/blind-spots: open research questions derived from the official records. */
export const GET = handle(async (req: Request) => {
  const q = parseQuery(req, Query, { arrays: ["categories"], numbers: PAGE_NUMBERS });
  const page = pageOf(q);
  const { dataset } = await load();
  const ini = q.initiative ? findInitiative(dataset, q.initiative) : undefined;
  if (q.initiative && !ini) throw notFound(`No initiative with id or slug "${q.initiative}"`);
  const items = blindSpots(dataset)
    .filter((b) => !ini || b.initiativeId === ini.id)
    .filter((b) => !q.categories?.length || q.categories.includes(b.category))
    .filter((b) => !q.importance || b.importance === q.importance)
    .map((b) => ({ ...b, categoryLabel: BLIND_SPOT_LABEL[b.category] }));
  return ok(dataset, paginate(items, page), {
    limitations: ["Blind spots are questions for reviewers, generated by fixed rules. They are not findings of wrongdoing or deficiency."],
  });
});
