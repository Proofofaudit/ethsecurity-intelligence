import { z } from "zod";
import { findInitiative, OPEN_QUESTION_CATEGORIES, OPEN_QUESTION_NOTICE, OPEN_QUESTION_RULES, OPEN_QUESTIONS_VERSION, openQuestionRows, openQuestionsFor } from "@/lib/intelligence/service";
import { handle, IdParam, load, notFound, ok, PAGE_NUMBERS, PageFields, pageOf, paginate, parseQuery } from "@/lib/api/http";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const Query = z
  .object({ initiative: IdParam.optional(), categories: z.array(z.enum(OPEN_QUESTION_CATEGORIES)).max(OPEN_QUESTION_CATEGORIES.length).optional(), ...PageFields })
  .strict();

/**
 * GET /api/v1/open-questions: rule-based open questions (open-questions@1). With ?initiative=
 * the questions of one initiative; without it the counts per category for every initiative,
 * alphabetical by title. Read-only; nothing is sent anywhere.
 */
export const GET = handle(async (req: Request) => {
  const q = parseQuery(req, Query, { arrays: ["categories"], numbers: PAGE_NUMBERS });
  const { dataset } = await load();
  const base = { method: OPEN_QUESTIONS_VERSION, notice: OPEN_QUESTION_NOTICE, rules: OPEN_QUESTION_RULES };
  const limitations = ["Open questions are generated by fixed rules from gaps in the official record. A question is not an accusation and not a finding."];
  if (!q.initiative) return ok(dataset, { ...base, order: "Alphabetical (neutral) by title.", rows: openQuestionRows(dataset) }, { limitations });
  const ini = findInitiative(dataset, q.initiative);
  if (!ini) throw notFound(`No initiative with id or slug "${q.initiative}"`);
  const items = (openQuestionsFor(dataset, ini.id) ?? []).filter((x) => !q.categories?.length || q.categories.includes(x.category));
  return ok(dataset, { ...base, order: "By category, then rule number.", ...paginate(items, pageOf(q)) }, { limitations, sources: [ini.url] });
});
