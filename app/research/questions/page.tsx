import type { Metadata } from "next";
import Link from "next/link";
import { Note, PageHead } from "@/components/ui/layout";
import { loadIntelligence } from "@/lib/intelligence/load";
import { OPEN_QUESTION_CATEGORIES, OPEN_QUESTION_NOTICE, OPEN_QUESTION_RULES, openQuestionRows } from "@/lib/intelligence/service";
import { NEUTRAL_SORT_LABEL } from "@/lib/neutralLanguage";

export const metadata: Metadata = { title: "Open questions" };
export const revalidate = 600;

/** Item 11 aggregate: rule-based open questions per category for every initiative, alphabetical. */
export default async function OpenQuestionsPage() {
  const { dataset: d } = await loadIntelligence();
  const rows = openQuestionRows(d);
  const totals = Object.fromEntries(OPEN_QUESTION_CATEGORIES.map((c) => [c, rows.reduce((s, r) => s + r.counts[c], 0)]));
  const grand = rows.reduce((s, r) => s + r.total, 0);
  return (
    <div className="space-y-8">
      <PageHead
        eyebrow="Research · Open questions"
        title="Open questions across the cohort"
        lede={
          <p>
            Questions generated by eight fixed rules from structural gaps in the official record, such as a milestone without a target date or a pledge not yet received. The same wording applies to every initiative. {OPEN_QUESTION_NOTICE}
          </p>
        }
      />

      <div className="overflow-x-auto">
        <table data-testid="open-question-table" className="w-full min-w-[720px] text-sm">
          <caption className="mb-2 text-left text-xs text-ink-3">
            {rows.length} initiatives · {NEUTRAL_SORT_LABEL} by title · counts of open questions per category
          </caption>
          <thead>
            <tr className="border-b border-ink text-left text-2xs tracking-wide text-ink-3 uppercase">
              <th scope="col" className="py-2 pr-2 font-medium">
                Initiative
              </th>
              {OPEN_QUESTION_CATEGORIES.map((c) => (
                <th key={c} scope="col" className="px-2 py-2 text-right font-medium">
                  {c}
                </th>
              ))}
              <th scope="col" className="py-2 pl-2 text-right font-medium">
                Total
              </th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.id} data-testid="open-question-row" className="border-b border-rule align-top">
                <td className="py-1.5 pr-2">
                  <Link href={`/initiatives/${r.slug}#questions`} className="hover:text-accent">
                    {r.title}
                  </Link>
                  {r.type === "rfp" && <span className="ml-2 text-2xs tracking-wide text-ink-3 uppercase">RFP</span>}
                </td>
                {OPEN_QUESTION_CATEGORIES.map((c) => (
                  <td key={c} className="num px-2 py-1.5 text-right">
                    {r.counts[c]}
                  </td>
                ))}
                <td className="num py-1.5 pl-2 text-right font-medium">{r.total}</td>
              </tr>
            ))}
          </tbody>
          <tfoot>
            <tr className="border-t border-ink text-ink-2">
              <th scope="row" className="py-2 pr-2 text-left font-medium">
                All initiatives
              </th>
              {OPEN_QUESTION_CATEGORIES.map((c) => (
                <td key={c} className="num px-2 py-2 text-right">
                  {totals[c]}
                </td>
              ))}
              <td className="num py-2 pl-2 text-right font-medium">{grand}</td>
            </tr>
          </tfoot>
        </table>
      </div>

      <section aria-labelledby="rules" className="max-w-[880px]">
        <h2 id="rules" className="eyebrow mb-2">
          Rules
        </h2>
        <ol className="divide-y divide-rule border-y border-rule text-sm">
          {OPEN_QUESTION_RULES.map((r) => (
            <li key={r.id} className="grid grid-cols-[28px_110px_1fr] gap-3 py-2 max-sm:grid-cols-[28px_1fr]">
              <span className="num text-ink-3">{r.n}</span>
              <span className="text-2xs tracking-wide text-ink-3 uppercase max-sm:hidden">{r.category}</span>
              <span>
                {r.label}. <span className="text-ink-3">Field: {r.field}. Question: “{r.template}”</span>
              </span>
            </li>
          ))}
        </ol>
        <Note className="mt-2">
          Counts are not a measure of quality: an initiative with more milestones or pledges has more records the rules can ask about. Marks you set on a dossier stay in this browser.{" "}
          <Link href="/methodology#open-questions" className="link">
            Method
          </Link>
        </Note>
      </section>
    </div>
  );
}
