import type { Metadata } from "next";
import Link from "next/link";
import { Tag } from "@/components/ui/button";
import { Note, PageHead } from "@/components/ui/layout";
import { loadIntelligence } from "@/lib/intelligence/load";
import { BLIND_SPOT_LABEL, blindSpots, displayName, findInitiative, type BlindSpot } from "@/lib/intelligence/service";
import { cn } from "@/lib/util/cn";

export const metadata: Metadata = { title: "Research blind spots" };
export const dynamic = "force-dynamic";

type SP = Promise<Record<string, string | string[] | undefined>>;
const one = (v: string | string[] | undefined) => (Array.isArray(v) ? v[0] : v) ?? "";
const GROUPS = ["initiative", "category", "importance"] as const;
type Group = (typeof GROUPS)[number];

const IMPORTANCE_LABEL: Record<BlindSpot["importance"], string> = { higher: "Higher research importance", standard: "Standard research importance" };

export default async function BlindSpotsPage({ searchParams }: { searchParams: SP }) {
  const sp = await searchParams;
  const { dataset: d } = await loadIntelligence();
  const group: Group = (GROUPS as readonly string[]).includes(one(sp.group)) ? (one(sp.group) as Group) : "initiative";
  const ini = one(sp.ini) ? findInitiative(d, one(sp.ini)) : undefined;
  const cat = one(sp.cat) in BLIND_SPOT_LABEL ? (one(sp.cat) as BlindSpot["category"]) : null;
  const imp = one(sp.imp) === "higher" || one(sp.imp) === "standard" ? (one(sp.imp) as BlindSpot["importance"]) : null;

  const all = blindSpots(d);
  const items = all.filter((b) => (!ini || b.initiativeId === ini.id) && (!cat || b.category === cat) && (!imp || b.importance === imp));
  const byId = new Map(d.initiatives.map((i) => [i.id, i]));
  const name = (id: string) => {
    const i = byId.get(id);
    return i ? displayName(d, i) : id;
  };
  const claimIds = new Set(d.claims.map((c) => c.id));
  const milestoneIds = new Set(d.milestones.map((m) => m.id));

  const keyOf = (b: BlindSpot) => (group === "initiative" ? name(b.initiativeId) : group === "category" ? BLIND_SPOT_LABEL[b.category] : IMPORTANCE_LABEL[b.importance]);
  const groups = new Map<string, BlindSpot[]>();
  for (const b of items) groups.set(keyOf(b), [...(groups.get(keyOf(b)) ?? []), b]);
  const sorted = [...groups.entries()].sort((a, b) => (group === "importance" ? (a[0].startsWith("Higher") ? -1 : 1) : a[0].localeCompare(b[0])));

  const href = (next: Partial<Record<"group" | "ini" | "cat" | "imp", string>>) => {
    const p = new URLSearchParams();
    const merged = { group, ini: ini?.slug ?? "", cat: cat ?? "", imp: imp ?? "", ...next };
    for (const [k, v] of Object.entries(merged)) if (v && !(k === "group" && v === "initiative")) p.set(k, v);
    const s = p.toString();
    return s ? `/research/blind-spots?${s}` : "/research/blind-spots";
  };
  const catCounts = Object.keys(BLIND_SPOT_LABEL).map((k) => ({ k: k as BlindSpot["category"], n: all.filter((b) => b.category === k && (!ini || b.initiativeId === ini.id)).length }));
  const pill = (active: boolean) => cn("hover:text-accent", active ? "font-semibold text-ink" : "text-ink-2");

  const refLink = (b: BlindSpot, ref: string) => {
    const slug = byId.get(b.initiativeId)?.slug;
    if (claimIds.has(ref)) return { href: `/initiatives/${slug}#claim=${ref}`, label: "Inspect the statement" };
    if (milestoneIds.has(ref)) return { href: `/initiatives/${slug}#milestones`, label: "See the milestone" };
    if (byId.has(ref)) return { href: `/research/compare?ids=${slug},${byId.get(ref)?.slug}`, label: `Compare with ${name(ref)}` };
    return null;
  };

  return (
    <div className="space-y-8">
      <PageHead
        eyebrow="Research · Blind spots"
        title="Questions the evidence record leaves open"
        lede={<p>Each item is a specific question generated by a fixed rule from the published record, such as an adoption milestone without public confirmation or an applicant figure without an independent source. Missing data is a reason to ask, never a finding against an initiative.</p>}
      />

      <div className="space-y-2 border-y border-rule py-3 text-sm">
        <div className="flex flex-wrap items-baseline gap-x-4 gap-y-1">
          <span className="eyebrow w-24">Group by</span>
          {GROUPS.map((g) => (
            <Link key={g} href={href({ group: g })} aria-current={group === g ? "true" : undefined} className={pill(group === g)}>
              {g === "initiative" ? "Initiative" : g === "category" ? "Category" : "Research importance"}
            </Link>
          ))}
        </div>
        <div className="flex flex-wrap items-baseline gap-x-4 gap-y-1">
          <span className="eyebrow w-24">Category</span>
          <Link href={href({ cat: "" })} className={pill(!cat)}>
            All
          </Link>
          {catCounts.map(({ k, n }) => (
            <Link key={k} href={href({ cat: k })} className={pill(cat === k)}>
              {BLIND_SPOT_LABEL[k]} <span className="num text-ink-3">{n}</span>
            </Link>
          ))}
        </div>
        <div className="flex flex-wrap items-baseline gap-x-4 gap-y-1">
          <span className="eyebrow w-24">Importance</span>
          <Link href={href({ imp: "" })} className={pill(!imp)}>
            All
          </Link>
          <Link href={href({ imp: "higher" })} className={pill(imp === "higher")}>
            Higher
          </Link>
          <Link href={href({ imp: "standard" })} className={pill(imp === "standard")}>
            Standard
          </Link>
        </div>
        {ini && (
          <p className="text-xs">
            Showing {name(ini.id)} only.{" "}
            <Link href={href({ ini: "" })} className="link">
              Show all initiatives
            </Link>
          </p>
        )}
      </div>

      <p className="text-sm text-ink-2" aria-live="polite">
        <span className="num">{items.length}</span> questions{ini ? "" : ` across ${new Set(items.map((b) => b.initiativeId)).size} initiatives`}.
      </p>

      {sorted.length === 0 ? (
        <p className="text-sm text-ink-3">No questions match these filters.</p>
      ) : (
        sorted.map(([g, list]) => (
          <section key={g} aria-label={g}>
            <h2 className="flex flex-wrap items-baseline justify-between gap-2 border-t border-ink pt-3">
              <span className="text-md font-semibold">
                {g} <span className="num text-sm font-normal text-ink-3">{list.length}</span>
              </span>
              {group === "initiative" && list[0] && (
                <Link href={`/initiatives/${byId.get(list[0].initiativeId)?.slug}#questions`} className="text-xs text-ink-3 hover:text-accent">
                  Open dossier
                </Link>
              )}
            </h2>
            <ol className="mt-1 divide-y divide-rule">
              {list.map((b) => (
                <li key={b.id} className="grid gap-x-8 gap-y-1 py-3 md:grid-cols-[minmax(0,1.3fr)_minmax(0,1fr)]">
                  <div className="min-w-0">
                    <p className="text-sm">{b.question}</p>
                    <p className="mt-1 flex flex-wrap items-center gap-2 text-2xs text-ink-3">
                      {group !== "initiative" && <span className="font-medium text-ink-2">{name(b.initiativeId)}</span>}
                      {group !== "category" && <Tag>{BLIND_SPOT_LABEL[b.category]}</Tag>}
                      {group !== "importance" && b.importance === "higher" && <Tag className="border-ink-3 text-ink">Higher importance</Tag>}
                    </p>
                  </div>
                  <div className="min-w-0 text-xs text-ink-3">
                    <p>
                      <span className="text-ink-2">Basis: </span>
                      {b.basis}
                    </p>
                    <p className="mt-1 flex flex-wrap gap-x-3">
                      {b.refs
                        .map((r) => refLink(b, r))
                        .filter((x) => !!x)
                        .map((x) => (
                          <Link key={x.href} href={x.href} className="link">
                            {x.label}
                          </Link>
                        ))}
                    </p>
                  </div>
                </li>
              ))}
            </ol>
          </section>
        ))
      )}

      <section className="border-t border-ink pt-3">
        <h2 className="text-md font-semibold">How questions are generated</h2>
        <ul className="mt-2 max-w-[860px] list-disc space-y-1 pl-5 text-sm text-ink-2">
          <li>Adoption dependency: every open adoption milestone. Higher importance when it holds 25% or more of the goal.</li>
          <li>Brief acceptance criterion: criteria shorter than 40 characters, or none recorded.</li>
          <li>Integration not confirmed: an integration the applicant states that has no independent confirmation. Higher importance.</li>
          <li>Statement without independent support: an applicant-reported figure.</li>
          <li>Maintenance not described: no sentence in the proposal mentions maintaining the work.</li>
          <li>No linked existing work: a grant for which the pipeline found no public repository, completed milestone or reachable recipient page. Higher importance.</li>
          <li>Possible overlap: a potentially overlapping pair from the collaboration analysis (a hypothesis).</li>
        </ul>
        <Note className="mt-2">Importance orders research effort only. It is not a score and says nothing about the quality of an initiative.</Note>
      </section>
    </div>
  );
}
