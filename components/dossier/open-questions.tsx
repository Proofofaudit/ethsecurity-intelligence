"use client";

import Link from "next/link";
import { CopyButton } from "@/components/lab/copy";
import { Note } from "@/components/ui/layout";
import { OfficialQuote, SourceLabel } from "@/components/ui/official-quote";
import { markOpenQuestion, useWorkspace } from "@/components/workspace/store";
import type { OpenQuestion } from "@/lib/intelligence/open-questions";

/**
 * Open questions (Item 11). The same component renders every dossier: one row per rule-based
 * question with its category, rule, the field or quoted text it comes from and a source link.
 * "Mark as asked or resolved" is stored only in this browser; nothing is sent to anyone.
 */
export function OpenQuestions({ items, notice, copyText, quoteSource }: { items: OpenQuestion[]; notice: string; copyText: string; quoteSource: string }) {
  const w = useWorkspace();
  const marked = items.filter((q) => w.openQuestions[q.id]).length;
  return (
    <div data-testid="open-questions" className="max-w-[880px] space-y-4">
      <p data-testid="open-questions-notice" className="border-l-2 border-ink pl-3 text-sm text-ink">
        {notice}
      </p>
      <Note>
        Generated by eight fixed rules from gaps in the official record. The wording is the same for every initiative. Marks are kept in this browser only; the app never sends questions to anyone.{" "}
        <Link href="/about#open-questions" className="link">
          Rules
        </Link>
      </Note>
      {items.length === 0 ? (
        <p className="text-sm text-ink-3">No rule raised a question for this initiative.</p>
      ) : (
        <>
          <div className="flex flex-wrap items-center gap-x-4 gap-y-2 text-xs text-ink-3">
            <CopyButton text={copyText} label="Copy as list" />
            <span className="num" data-testid="open-questions-marked">
              {marked} of {items.length} marked as asked or resolved
            </span>
          </div>
          <ol className="divide-y divide-rule border-y border-rule">
            {items.map((q) => {
              const on = !!w.openQuestions[q.id];
              return (
                <li key={q.id} data-testid="open-question" data-rule={q.ruleId} data-category={q.category} data-marked={on ? "true" : "false"} className="grid grid-cols-[110px_1fr] gap-x-4 gap-y-1 py-3 text-sm max-sm:grid-cols-1">
                  <span className="text-2xs tracking-wide text-ink-3 uppercase">{q.category}</span>
                  <div className="min-w-0 space-y-1.5">
                    <p className={on ? "text-ink-3" : "text-ink"}>{q.question}</p>
                    <p className="text-xs text-ink-3">
                      Rule {q.ruleNumber}: {q.ruleLabel} · Field <code className="text-2xs">{q.field}</code>: {q.value}
                    </p>
                    {q.details.length > 0 && <p className="text-xs text-ink-3">{q.details.join(" · ")}</p>}
                    {q.quotes.map((t, i) => (
                      <OfficialQuote key={i} kind={q.quoteKind ?? "official"} source={q.sourceUrl} sourceName={q.sourceName === "Official proposal" ? "the official proposal" : quoteSource} className="[overflow-wrap:anywhere]">
                        {t}
                      </OfficialQuote>
                    ))}
                    <div className="flex flex-wrap items-center gap-x-4 gap-y-1 text-xs">
                      <SourceLabel kind={q.sourceKind} />
                      <a href={q.sourceUrl} className="link break-all" rel="noreferrer">
                        {q.sourceName}
                      </a>
                      <label className="inline-flex cursor-pointer items-center gap-1.5 text-ink-2">
                        <input type="checkbox" data-testid="open-question-mark" checked={on} onChange={(e) => markOpenQuestion(q.id, e.target.checked)} className="size-3.5 accent-[var(--accent)]" />
                        Mark as asked or resolved
                      </label>
                    </div>
                  </div>
                </li>
              );
            })}
          </ol>
        </>
      )}
    </div>
  );
}
